import { TRANSIT } from "@/assets/data/transit";
import { areaDriveMinutes } from "@/lib/areas";
import { distanceMeters } from "@/lib/utils/geoDistance";
import type { Site } from "@/lib/models";

// Trip items carry only a place id, so whoever works out travel hands in a way to look a
// place up: the live place list (lib/hooks/usePlaceLookup.ts), never a bundled copy,
// because places are added and re-homed in the admin panel at any time.
export type PlaceLookup = (siteId: string) => (Pick<Site, "area"> & Partial<Pick<Site, "lat" | "lng">>) | undefined;

// Roads wind: about 1.3 times the straight line, at about 50 km/h on the roads around a
// town, so about 1.6 minutes for each kilometre as the crow flies.
// ponytail: one figure for every town. A town whose roads read wrong gets its own table
// (scripts/generate-drive-times.js towns --area <id>), which always wins over this.
const MINUTES_PER_STRAIGHT_KM = (1.3 / 50) * 60;

// `drive` is set only when the leg crosses from one area to another with a listed time:
// that, not its length, is what makes the day view draw it as a drive block.
export type Leg = { slots: number; drive: { fromArea: string; toArea: string } | null };

export function getLeg(fromSiteId: string, toSiteId: string, places: PlaceLookup): Leg {
  if (fromSiteId === toSiteId) return { slots: 0, drive: null };

  const fromArea = places(fromSiteId)?.area;
  const toArea = places(toSiteId)?.area;
  const minutes = fromArea && toArea ? areaDriveMinutes(fromArea, toArea) : undefined;
  if (fromArea && toArea && minutes !== undefined) {
    return { slots: Math.max(1, Math.ceil(minutes / 30)), drive: { fromArea, toArea } };
  }

  // Two places in one area: that area's own table (one per area, generated by
  // scripts/generate-drive-times.js towns), never another area's.
  const from = places(fromSiteId);
  const to = places(toSiteId);
  if (fromArea && fromArea === toArea) {
    const slots = TRANSIT[fromArea]?.[fromSiteId]?.[toSiteId];
    if (slots !== undefined) return { slots, drive: null };
  }

  // Not in a table (a place added since it was made, an area without one, a pair of areas
  // with no listed time, a place with no area): estimated from the distance, at least the
  // half hour. With no position to go on, the half hour, so scheduling never breaks.
  if (from?.lat != null && from.lng != null && to?.lat != null && to.lng != null) {
    const km = distanceMeters({ lat: from.lat, lng: from.lng }, { lat: to.lat, lng: to.lng }) / 1000;
    return { slots: Math.max(1, Math.ceil((km * MINUTES_PER_STRAIGHT_KM) / 30)), drive: null };
  }
  return { slots: 1, drive: null };
}
